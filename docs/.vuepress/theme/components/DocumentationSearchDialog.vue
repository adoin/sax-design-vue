<script setup lang="ts">
import {
  computed,
  nextTick,
  shallowRef,
  useId,
  useTemplateRef,
  watch,
} from 'vue'
import { useRouteLocale } from '@vuepress/client'
// @ts-ignore
import { useThemeData } from '@vuepress/plugin-theme-data/client'
import { useRouter } from 'vue-router'
import { SConfigProvider } from '@vuesax-alpha/components/config-provider'
import zhCN from '@vuesax-alpha/locale/lang/zh-cn'
import en from '@vuesax-alpha/locale/lang/en'
import { SDialog } from '@vuesax-alpha/components/dialog'
import { SFocusTrap } from '@vuesax-alpha/components/focus-trap'
import { SInput } from '@vuesax-alpha/components/input'
import { SButton } from '@vuesax-alpha/components/button'
import { SIcon } from '@vuesax-alpha/components/icon'
import {
  searchDocumentation,
  searchNavigationAction,
} from '../util/documentation-search'
import SearchMatch from './SearchMatch.vue'
import type { DocumentationSearchEntry } from '../util/documentation-search'
import type { InputInstance } from '@vuesax-alpha/components/input'
import type { SaxDesignVueThemeOptions } from '../saxDesignVueTheme'
const props = defineProps<{ returnFocusTo?: HTMLElement | null }>()
const open = defineModel<boolean>('open', { required: true })
const emit = defineEmits<{ closed: [] }>()
const router = useRouter()
const locale = useRouteLocale()
const zh = computed(() => locale.value.startsWith('/zh/'))
const theme = useThemeData<SaxDesignVueThemeOptions>()
const title = computed(() =>
  zh.value ? '搜索组件与文档' : 'Search components and documentation',
)
const input = useTemplateRef<InputInstance>('input')
const dialog = useTemplateRef<HTMLElement>('dialog')
const query = shallowRef('')
const entries = shallowRef<DocumentationSearchEntry[]>([])
const loading = shallowRef(false)
const failed = shallowRef(false)
const focusIndex = shallowRef(0)
const listId = `docs-search-${useId()}`
let pending: Promise<void> | undefined
const groups = computed(() => {
  const trimmed = query.value.trim()
  const results = trimmed
    ? searchDocumentation(
        entries.value,
        trimmed,
        locale.value,
        Math.max(12, theme.value.searchMaxSuggestions ?? 5),
      )
    : entries.value
        .filter(
          (entry) =>
            entry.locale === locale.value &&
            !entry.header &&
            entry.path.includes('/components/'),
        )
        .slice(0, 12)
        .map((entry) => ({ ...entry, snippet: '' }))
  const buckets = [
    { label: zh.value ? '组件' : 'Components', rows: [] as typeof results },
    {
      label: zh.value ? '文档内容' : 'Documentation',
      rows: [] as typeof results,
    },
    { label: zh.value ? '指南' : 'Guides', rows: [] as typeof results },
  ]
  results.forEach((result) => {
    const component = result.path.includes('/components/')
    const nameMatch = `${result.title} ${result.keywords ?? ''}`
      .toLocaleLowerCase()
      .includes(trimmed.toLocaleLowerCase())
    buckets[component && nameMatch ? 0 : component ? 1 : 2].rows.push(result)
  })
  let index = 0
  return buckets
    .filter((bucket) => bucket.rows.length)
    .map((bucket) => ({
      ...bucket,
      rows: bucket.rows.map((row) => ({ ...row, index: index++ })),
    }))
})
const results = computed(() => groups.value.flatMap((group) => group.rows))
function loadIndex() {
  if (pending) return pending
  loading.value = true
  failed.value = false
  // @ts-ignore Generated by VuePress before client bundling.
  pending = import('@temp/documentation-search/index.js')
    .then((module) => {
      entries.value = module.default
    })
    .catch(() => {
      failed.value = true
      pending = undefined
    })
    .finally(() => {
      loading.value = false
    })
  return pending
}
function focus() {
  input.value?.focus()
}
function onInputKeydown(event: KeyboardEvent) {
  if ((event.isComposing || event.keyCode === 229) && event.key === 'Escape')
    event.stopPropagation()
  const action = searchNavigationAction(event)
  if (!action) return
  event.preventDefault()
  if (action === 'open') go(focusIndex.value)
  else move(action === 'next' ? 1 : -1)
}
function move(direction: number) {
  if (!results.value.length) return
  focusIndex.value =
    (focusIndex.value + direction + results.value.length) % results.value.length
  nextTick(() =>
    dialog.value
      ?.querySelector(`#${listId}-${focusIndex.value}`)
      ?.scrollIntoView({ block: 'nearest' }),
  )
}
function go(index: number) {
  const result = results.value[index]
  if (!result) return
  open.value = false
  router.push(result.path)
}
async function onClosed() {
  await nextTick()
  if (props.returnFocusTo?.isConnected) props.returnFocusTo.focus()
  emit('closed')
}
watch(open, (value) => {
  if (value) {
    focusIndex.value = 0
    loadIndex()
  }
})
watch(query, () => {
  focusIndex.value = 0
})
watch(locale, () => {
  query.value = ''
  open.value = false
})
defineExpose({ focus })
</script>
<template>
  <SDialog
    v-model="open"
    :title="title"
    width="min(800px, calc(100vw - 32px))"
    lock-scroll
    not-close
    not-padding
    overlay-blur
    :show-header="false"
    :close-animation="false"
    :mask-closable="true"
    @opened="focus"
    @closed="onClosed"
  >
    <SConfigProvider :locale="zh ? zhCN : en">
      <SFocusTrap
        :trapped="open"
        :loop="true"
        :focus-trap-el="dialog || undefined"
        @release-requested="open = false"
      >
        <section
          ref="dialog"
          class="docs-search-dialog"
          tabindex="-1"
          @keydown.esc.prevent="open = false"
        >
          <header class="docs-search-header">
            <SInput
              ref="input"
              v-model="query"
              class="docs-search-field"
              size="large"
              clearable
              block
              :aria-label="title"
              :placeholder="
                zh
                  ? '搜索组件、章节或文档正文'
                  : 'Search components, headings, or documentation'
              "
              role="combobox"
              aria-autocomplete="list"
              :aria-controls="listId"
              :aria-expanded="!!results.length"
              :aria-activedescendant="
                results.length ? `${listId}-${focusIndex}` : undefined
              "
              @keydown="onInputKeydown"
            >
              <template #prefix
                ><SIcon name="cb:search" size="20px"
              /></template>
            </SInput>
            <SButton
              icon
              type="flat"
              :aria-label="zh ? '关闭搜索' : 'Close search'"
              @click="open = false"
              ><SIcon name="cb:close" size="20px"
            /></SButton>
          </header>
          <div class="docs-search-body">
            <p v-if="!query.trim()" class="docs-search-hint">
              {{
                zh
                  ? '输入关键词，搜索组件名称、章节和文档正文。'
                  : 'Search component names, headings, and documentation text.'
              }}
            </p>
            <div
              :id="listId"
              role="listbox"
              :aria-label="zh ? '搜索结果' : 'Search results'"
            >
              <section
                v-for="group in groups"
                :key="group.label"
                class="docs-search-group"
                role="group"
                :aria-label="group.label"
              >
                <h3>{{ group.label }}</h3>
                <div
                  v-for="result in group.rows"
                  :id="`${listId}-${result.index}`"
                  :key="result.path"
                  class="docs-search-result"
                  :class="{
                    selected: result.index === focusIndex,
                    'is-section': !!result.header,
                  }"
                  role="option"
                  :aria-selected="result.index === focusIndex"
                  @mouseenter="focusIndex = result.index"
                  @mousedown.prevent
                  @click="go(result.index)"
                >
                  <svg
                    v-if="result.header"
                    width="20"
                    height="20"
                    viewBox="0 0 24 24"
                    fill="none"
                    aria-hidden="true"
                  >
                    <path
                      d="M10 3 8 21M16 3l-2 18M4 9h16M3 15h16"
                      stroke="currentColor"
                      stroke-width="1.6"
                      stroke-linecap="round"
                    />
                  </svg>
                  <SIcon v-else name="cb:document" size="20px" />
                  <div class="docs-search-result-copy">
                    <strong
                      ><SearchMatch
                        :text="result.header || result.title"
                        :query="query"
                    /></strong>
                    <small v-if="result.header"
                      ><SearchMatch :text="result.title" :query="query"
                    /></small>
                    <p v-if="result.snippet && query">
                      <SearchMatch :text="result.snippet" :query="query" />
                    </p>
                  </div>
                  <SIcon
                    v-if="result.index === focusIndex"
                    class="docs-search-enter"
                    name="cb:arrow-right"
                    size="18px"
                  />
                </div>
              </section>
            </div>
            <p v-if="!results.length" class="docs-search-empty" role="status">
              {{
                loading
                  ? zh
                    ? '正在准备搜索索引…'
                    : 'Loading search index…'
                  : failed
                    ? zh
                      ? '索引加载失败，请重新打开搜索。'
                      : 'Search index failed to load. Reopen search to retry.'
                    : zh
                      ? '没有找到匹配内容，试试其他关键词。'
                      : 'No matches. Try another keyword.'
              }}
            </p>
          </div>
          <footer class="docs-search-footer">
            <span><kbd>↑</kbd><kbd>↓</kbd> {{ zh ? '切换' : 'Navigate' }}</span
            ><span><kbd>↵</kbd> {{ zh ? '打开' : 'Open' }}</span
            ><span><kbd>Esc</kbd> {{ zh ? '关闭' : 'Close' }}</span
            ><span class="docs-search-count">{{
              zh ? '组件与文档全文搜索' : 'Components & documentation search'
            }}</span>
          </footer>
        </section>
      </SFocusTrap>
    </SConfigProvider>
  </SDialog>
</template>
